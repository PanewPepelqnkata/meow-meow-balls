-- Enable RLS on all tables
alter default privileges in schema public grant all on tables to postgres, anon, authenticated, service_role;

-- Users table (extends Supabase auth.users)
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  username text unique,
  avatar_url text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- High scores / leaderboard
create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade not null,
  score integer not null,
  tier_reached integer not null,
  balls_merged integer not null default 0,
  duration_ms integer not null default 0,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Indexes for leaderboard queries
create index if not exists scores_user_id_idx on public.scores(user_id);
create index if not exists scores_score_idx on public.scores(score desc);
create index if not exists scores_created_at_idx on public.scores(created_at desc);

-- RLS Policies
alter table public.profiles enable row level security;
alter table public.scores enable row level security;

-- Profiles: users can read all profiles, but only update their own
create policy "Public profiles are viewable by everyone"
  on public.profiles for select
  using (true);

create policy "Users can insert their own profile"
  on public.profiles for insert
  with check (auth.uid() = id);

create policy "Users can update their own profile"
  on public.profiles for update
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- Scores: users can read all scores, but only insert their own
create policy "Scores are viewable by everyone"
  on public.scores for select
  using (true);

create policy "Users can insert their own scores"
  on public.scores for insert
  with check (auth.uid() = user_id);

-- Function to handle new user signup
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, username, avatar_url)
  values (new.id, new.raw_user_meta_data->>'username', new.raw_user_meta_data->>'avatar_url');
  return new;
end;
$$ language plpgsql security definer;

-- Trigger for new user signup
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
