-- 6. Link a guest profile + its runs when the guest registers an account
create or replace function public.link_guest_to_user(p_guest_id uuid)
returns void
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_uid uuid := (select auth.uid());
begin
  if v_uid is null or p_guest_id is null then
    return;
  end if;

  update public.guest_profiles
  set
    converted_user_id = v_uid,
    converted_at = coalesce(converted_at, now()),
    updated_at = now(),
    last_seen_at = now()
  where guest_id = p_guest_id;

  -- Copy any guest runs into the newly registered user's scores if they have no scores yet
  if not exists (select 1 from public.scores where user_id = v_uid) then
    insert into public.scores (user_id, score, tier_reached, balls_merged, duration_ms, created_at)
    select v_uid, gs.score, gs.tier_reached, gs.balls_merged, gs.duration_ms, gs.created_at
    from public.guest_scores gs
    where gs.guest_id = p_guest_id;
  end if;

  perform public.boss_sync_user_progress_internal(v_uid, false);
end;
$$;

revoke all on function public.link_guest_to_user(uuid) from public, anon;
grant execute on function public.link_guest_to_user(uuid) to authenticated;

-- 7. Upgrade boss_get_dashboard_data to include guest_profiles and guest_scores
create or replace function public.boss_get_dashboard_data()
returns jsonb
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_profiles jsonb;
  v_scores jsonb;
  v_progress jsonb;
  v_guest_profiles jsonb;
  v_guest_scores jsonb;
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required';
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', p.id,
        'username', p.username,
        'display_name', p.display_name,
        'email', coalesce(p.email, u.email),
        'avatar_url', p.avatar_url,
        'created_at', p.created_at,
        'updated_at', p.updated_at,
        'last_sign_in_at', u.last_sign_in_at
      )
      order by p.created_at desc
    ),
    '[]'::jsonb
  )
  into v_profiles
  from public.profiles p
  left join auth.users u on u.id = p.id;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', s.id,
        'user_id', s.user_id,
        'score', s.score,
        'tier_reached', s.tier_reached,
        'balls_merged', s.balls_merged,
        'duration_ms', s.duration_ms,
        'created_at', s.created_at
      )
      order by s.created_at desc
    ),
    '[]'::jsonb
  )
  into v_scores
  from public.scores s;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'user_id', up.user_id,
        'best_score', up.best_score,
        'discovered', up.discovered,
        'variants', up.variants,
        'stats', up.stats,
        'leaderboard', up.leaderboard,
        'settings', up.settings,
        'updated_at', up.updated_at
      )
    ),
    '[]'::jsonb
  )
  into v_progress
  from public.user_progress up;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'guest_id', gp.guest_id,
        'best_score', gp.best_score,
        'discovered', gp.discovered,
        'variants', gp.variants,
        'stats', gp.stats,
        'leaderboard', gp.leaderboard,
        'settings', gp.settings,
        'converted_user_id', gp.converted_user_id,
        'converted_at', gp.converted_at,
        'created_at', gp.created_at,
        'updated_at', gp.updated_at,
        'last_seen_at', gp.last_seen_at
      )
      order by gp.last_seen_at desc
    ),
    '[]'::jsonb
  )
  into v_guest_profiles
  from public.guest_profiles gp;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', gs.id,
        'guest_id', gs.guest_id,
        'score', gs.score,
        'tier_reached', gs.tier_reached,
        'balls_merged', gs.balls_merged,
        'duration_ms', gs.duration_ms,
        'created_at', gs.created_at
      )
      order by gs.created_at desc
    ),
    '[]'::jsonb
  )
  into v_guest_scores
  from public.guest_scores gs;

  return jsonb_build_object(
    'profiles', v_profiles,
    'scores', v_scores,
    'progress', v_progress,
    'guest_profiles', v_guest_profiles,
    'guest_scores', v_guest_scores,
    'generated_at', now()
  );
end;
$$;

revoke all on function public.boss_get_dashboard_data() from public, anon;
grant execute on function public.boss_get_dashboard_data() to authenticated;

