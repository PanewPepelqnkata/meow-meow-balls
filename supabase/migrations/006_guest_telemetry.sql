-- Guest Telemetry & Anonymous Analytics for Boss Dashboard
-- Tracks anonymous/guest sessions, runs, progression, and conversion to registered accounts.

-- 1. Guest profiles / progression table
create table if not exists public.guest_profiles (
  guest_id uuid primary key,
  best_score integer not null default 0,
  discovered jsonb not null default '{}'::jsonb,
  variants jsonb not null default '{}'::jsonb,
  stats jsonb not null default '{"runs": 0, "merges": 0, "bestTier": 0}'::jsonb,
  leaderboard jsonb not null default '[]'::jsonb,
  settings jsonb not null default '{"theme": "auto"}'::jsonb,
  converted_user_id uuid references public.profiles(id) on delete set null,
  converted_at timestamp with time zone,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  last_seen_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index if not exists idx_guest_profiles_converted_user on public.guest_profiles(converted_user_id);
create index if not exists idx_guest_profiles_last_seen on public.guest_profiles(last_seen_at desc);

alter table public.guest_profiles enable row level security;

drop policy if exists "Authenticated users can view all guest profiles" on public.guest_profiles;
create policy "Authenticated users can view all guest profiles"
  on public.guest_profiles for select
  to authenticated
  using ((select auth.uid()) is not null);

-- 2. Guest runs / scores table
create table if not exists public.guest_scores (
  id bigint generated by default as identity primary key,
  guest_id uuid not null references public.guest_profiles(guest_id) on delete cascade,
  score integer not null default 0,
  tier_reached integer not null default 1,
  balls_merged integer not null default 0,
  duration_ms integer not null default 0,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index if not exists idx_guest_scores_guest_id on public.guest_scores(guest_id);
create index if not exists idx_guest_scores_created_at on public.guest_scores(created_at desc);

alter table public.guest_scores enable row level security;

drop policy if exists "Authenticated users can view all guest scores" on public.guest_scores;
create policy "Authenticated users can view all guest scores"
  on public.guest_scores for select
  to authenticated
  using ((select auth.uid()) is not null);

-- 3. Internal helper to synchronize guest_profiles from guest_scores + existing state
create or replace function public.boss_sync_guest_progress_internal(
  target_guest_id uuid,
  strict_from_scores boolean default false
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_max_score integer := 0;
  v_max_tier integer := 0;
  v_run_count integer := 0;
  v_total_merges integer := 0;
  v_leaderboard jsonb := '[]'::jsonb;
  v_existing public.guest_profiles%rowtype;
  v_has_existing boolean := false;
  v_discovered jsonb := '{}'::jsonb;
  v_variants jsonb := '{}'::jsonb;
  v_settings jsonb := '{"theme": "auto"}'::jsonb;
  v_stats jsonb;
  v_now_ms bigint := (extract(epoch from now()) * 1000)::bigint;
  v_t integer;
begin
  select
    coalesce(max(gs.score), 0),
    coalesce(max(gs.tier_reached), 0),
    count(*)::integer,
    coalesce(sum(gs.balls_merged), 0)::integer
  into v_max_score, v_max_tier, v_run_count, v_total_merges
  from public.guest_scores gs
  where gs.guest_id = target_guest_id;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'score', sub.score,
        'bestTier', sub.tier_reached,
        'at', (extract(epoch from sub.created_at) * 1000)::bigint
      )
      order by sub.score desc, sub.created_at desc
    ),
    '[]'::jsonb
  )
  into v_leaderboard
  from (
    select gs.score, gs.tier_reached, gs.created_at
    from public.guest_scores gs
    where gs.guest_id = target_guest_id
    order by gs.score desc, gs.created_at desc
    limit 10
  ) sub;

  select * into v_existing
  from public.guest_profiles gp
  where gp.guest_id = target_guest_id;
  v_has_existing := found;

  if v_has_existing then
    v_discovered := coalesce(v_existing.discovered, '{}'::jsonb);
    v_variants := coalesce(v_existing.variants, '{}'::jsonb);
    v_settings := coalesce(v_existing.settings, '{"theme": "auto"}'::jsonb);
    if not strict_from_scores then
      v_max_score := greatest(v_max_score, coalesce(v_existing.best_score, 0));
      v_run_count := greatest(v_run_count, coalesce((v_existing.stats->>'runs')::integer, 0));
      v_total_merges := greatest(v_total_merges, coalesce((v_existing.stats->>'merges')::integer, 0));
      v_max_tier := greatest(v_max_tier, coalesce((v_existing.stats->>'bestTier')::integer, 0));
    end if;
  end if;

  if strict_from_scores then
    v_discovered := jsonb_build_object('1', v_now_ms, '2', v_now_ms, '3', v_now_ms);
  else
    v_discovered := jsonb_build_object('1', v_now_ms, '2', v_now_ms, '3', v_now_ms) || v_discovered;
  end if;

  for v_t in 1..least(12, greatest(3, v_max_tier)) loop
    if not (v_discovered ? v_t::text) then
      v_discovered := v_discovered || jsonb_build_object(v_t::text, v_now_ms);
    end if;
  end loop;

  v_stats := jsonb_build_object(
    'runs', v_run_count,
    'merges', v_total_merges,
    'bestTier', v_max_tier
  );

  insert into public.guest_profiles (
    guest_id,
    best_score,
    discovered,
    variants,
    stats,
    leaderboard,
    settings,
    updated_at,
    last_seen_at
  )
  values (
    target_guest_id,
    v_max_score,
    v_discovered,
    v_variants,
    v_stats,
    v_leaderboard,
    v_settings,
    now(),
    now()
  )
  on conflict (guest_id) do update set
    best_score = excluded.best_score,
    discovered = excluded.discovered,
    variants = excluded.variants,
    stats = excluded.stats,
    leaderboard = excluded.leaderboard,
    settings = excluded.settings,
    updated_at = excluded.updated_at;
end;
$$;

revoke all on function public.boss_sync_guest_progress_internal(uuid, boolean) from public, anon, authenticated;

-- 4. Public telemetry RPC: upsert guest progression (callable by anon and authenticated)
create or replace function public.upsert_guest_progress(
  p_guest_id uuid,
  p_best_score integer,
  p_discovered jsonb default '{}'::jsonb,
  p_variants jsonb default '{}'::jsonb,
  p_stats jsonb default '{"runs": 0, "merges": 0, "bestTier": 0}'::jsonb,
  p_leaderboard jsonb default '[]'::jsonb,
  p_settings jsonb default '{"theme": "auto"}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_runs integer := greatest(0, coalesce((p_stats->>'runs')::integer, 0));
  v_merges integer := greatest(0, coalesce((p_stats->>'merges')::integer, 0));
  v_best_tier integer := greatest(0, least(12, coalesce((p_stats->>'bestTier')::integer, 0)));
  v_best integer := greatest(0, coalesce(p_best_score, 0));
begin
  if p_guest_id is null then
    return;
  end if;

  insert into public.guest_profiles (
    guest_id,
    best_score,
    discovered,
    variants,
    stats,
    leaderboard,
    settings,
    updated_at,
    last_seen_at
  )
  values (
    p_guest_id,
    v_best,
    coalesce(p_discovered, '{}'::jsonb),
    coalesce(p_variants, '{}'::jsonb),
    jsonb_build_object('runs', v_runs, 'merges', v_merges, 'bestTier', v_best_tier),
    coalesce(p_leaderboard, '[]'::jsonb),
    coalesce(p_settings, '{"theme": "auto"}'::jsonb),
    now(),
    now()
  )
  on conflict (guest_id) do update set
    best_score = greatest(public.guest_profiles.best_score, excluded.best_score),
    discovered = public.guest_profiles.discovered || excluded.discovered,
    variants = public.guest_profiles.variants || excluded.variants,
    stats = jsonb_build_object(
      'runs', greatest(coalesce((public.guest_profiles.stats->>'runs')::integer, 0), v_runs),
      'merges', greatest(coalesce((public.guest_profiles.stats->>'merges')::integer, 0), v_merges),
      'bestTier', greatest(coalesce((public.guest_profiles.stats->>'bestTier')::integer, 0), v_best_tier)
    ),
    leaderboard = case
      when jsonb_array_length(excluded.leaderboard) > 0 then excluded.leaderboard
      else public.guest_profiles.leaderboard
    end,
    settings = excluded.settings,
    updated_at = now(),
    last_seen_at = now();

  -- Backfill historical local leaderboard runs if guest_scores has no rows for this guest yet
  if jsonb_typeof(p_leaderboard) = 'array' and jsonb_array_length(p_leaderboard) > 0 then
    if not exists (select 1 from public.guest_scores where guest_id = p_guest_id) then
      insert into public.guest_scores (guest_id, score, tier_reached, balls_merged, duration_ms, created_at)
      select
        p_guest_id,
        greatest(0, coalesce((item->>'score')::integer, 0)),
        greatest(1, least(12, coalesce((item->>'bestTier')::integer, 1))),
        0,
        0,
        case
          when (item->>'at') is not null and (item->>'at') ~ '^[0-9]+$'
            then to_timestamp(((item->>'at')::bigint) / 1000.0)
          else now()
        end
      from jsonb_array_elements(p_leaderboard) as item
      where coalesce((item->>'score')::integer, 0) > 0;
    end if;
  end if;

  perform public.boss_sync_guest_progress_internal(p_guest_id, false);
end;
$$;

grant execute on function public.upsert_guest_progress(uuid, integer, jsonb, jsonb, jsonb, jsonb, jsonb) to anon, authenticated;

-- 5. Public telemetry RPC: record or update an anonymous guest run (callable by anon and authenticated)
drop function if exists public.record_guest_score(uuid, integer, integer, integer, integer);

create or replace function public.record_guest_score(
  p_guest_id uuid,
  p_score integer,
  p_tier_reached integer,
  p_balls_merged integer,
  p_duration_ms integer,
  p_score_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id bigint;
  v_score integer := greatest(0, coalesce(p_score, 0));
  v_tier integer := greatest(1, least(12, coalesce(p_tier_reached, 1)));
  v_merges integer := greatest(0, coalesce(p_balls_merged, 0));
  v_duration integer := greatest(0, coalesce(p_duration_ms, 0));
begin
  if p_guest_id is null then
    raise exception 'guest_id is required';
  end if;

  insert into public.guest_profiles (guest_id, best_score, updated_at, last_seen_at)
  values (p_guest_id, v_score, now(), now())
  on conflict (guest_id) do update set
    last_seen_at = now();

  if p_score_id is not null then
    update public.guest_scores
    set
      score = greatest(public.guest_scores.score, v_score),
      tier_reached = greatest(public.guest_scores.tier_reached, v_tier),
      balls_merged = greatest(public.guest_scores.balls_merged, v_merges),
      duration_ms = greatest(public.guest_scores.duration_ms, v_duration)
    where id = p_score_id and guest_id = p_guest_id
    returning id into v_id;
  end if;

  if v_id is null then
    insert into public.guest_scores (
      guest_id,
      score,
      tier_reached,
      balls_merged,
      duration_ms
    )
    values (
      p_guest_id,
      v_score,
      v_tier,
      v_merges,
      v_duration
    )
    returning id into v_id;
  end if;

  perform public.boss_sync_guest_progress_internal(p_guest_id, false);
  return v_id;
end;
$$;

grant execute on function public.record_guest_score(uuid, integer, integer, integer, integer, bigint) to anon, authenticated;

-- 5b. Authenticated run RPC: record or update an authenticated user's active run
create or replace function public.record_user_score(
  p_score integer,
  p_tier_reached integer,
  p_balls_merged integer,
  p_duration_ms integer,
  p_score_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
declare
  v_uid uuid := (select auth.uid());
  v_id bigint;
  v_score integer := greatest(0, coalesce(p_score, 0));
  v_tier integer := greatest(1, least(12, coalesce(p_tier_reached, 1)));
