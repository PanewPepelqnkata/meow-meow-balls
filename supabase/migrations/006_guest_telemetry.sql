    where id = p_score_id and user_id = v_uid
    returning id into v_id;
  end if;

  if v_id is null then
    insert into public.scores (
      user_id,
      score,
      tier_reached,
      balls_merged,
      duration_ms
    )
    values (
      v_uid,
      v_score,
      v_tier,
      v_merges,
      v_duration
    )
    returning id into v_id;
  end if;

  perform public.boss_sync_user_progress_internal(v_uid, false);
  return v_id;
end;
$$;

