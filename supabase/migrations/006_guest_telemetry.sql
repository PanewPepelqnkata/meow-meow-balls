create or replace function public.boss_reset_guest_progress(target_guest_id uuid)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if (select auth.uid()) is null then
    raise exception 'Authentication required';
  end if;

  delete from public.guest_scores where guest_id = target_guest_id;
  update public.guest_profiles
  set
    best_score = 0,
    discovered = '{}'::jsonb,
    variants = '{}'::jsonb,
    stats = '{"runs": 0, "merges": 0, "bestTier": 0}'::jsonb,
    leaderboard = '[]'::jsonb,
    updated_at = now()
  where guest_id = target_guest_id;

  perform public.boss_sync_guest_progress_internal(target_guest_id, true);
end;
$$;

