create or replace function public.submit_game_session(
  p_session_id uuid,
  p_score integer,
  p_tier_reached integer,
  p_balls_merged integer,
  p_duration_ms integer,
  p_interruption_reason text default 'completed',
  p_collectibles jsonb default null,
  p_guest_id uuid default null,
  p_nonce text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_session public.game_sessions%rowtype;
  v_score_id bigint;
  v_progress public.user_progress%rowtype;
  v_elapsed_ms bigint;
  v_risk_level text := 'NORMAL';
  v_risk_reasons jsonb := '[]'::jsonb;
begin
  if p_session_id is null then
    raise exception 'session_id is required' using errcode = '22023';
  end if;

  select * into v_session
  from public.game_sessions gs
  where gs.id = p_session_id
  for update;

  if not found then
    raise exception 'Game session not found' using errcode = '42501';
  end if;

  if v_uid is not null then
    if v_session.user_id is distinct from v_uid then
      raise exception 'Session does not belong to authenticated user' using errcode = '42501';
    end if;
  else
    if p_guest_id is null or v_session.guest_id is distinct from p_guest_id then
      raise exception 'Session does not belong to guest' using errcode = '42501';
    end if;
  end if;

  if p_nonce is not null and v_session.nonce <> p_nonce then
    raise exception 'Invalid session nonce' using errcode = '42501';
  end if;

  if v_session.status <> 'active' then
    raise exception 'Game session already submitted or closed' using errcode = '22023';
  end if;

  if v_session.expires_at <= now() then
    update public.game_sessions
    set status = 'expired', ended_at = coalesce(ended_at, now())
    where id = p_session_id;
    raise exception 'Game session has expired' using errcode = '22023';
  end if;

  begin
    perform public.validate_run_metrics(p_score, p_tier_reached, p_balls_merged, p_duration_ms);
  exception when others then
    update public.game_sessions
    set status = 'rejected',
        risk_level = 'INVALID',
        risk_reasons = jsonb_build_array(sqlerrm),
        ended_at = now()
    where id = p_session_id;
    raise;
  end;

  v_elapsed_ms := greatest(0, (extract(epoch from (now() - v_session.started_at)) * 1000)::bigint);
  if coalesce(p_duration_ms, 0) > v_elapsed_ms + 15000 then
    v_risk_level := 'SUSPICIOUS';
    v_risk_reasons := v_risk_reasons || jsonb_build_array('reported_duration_exceeds_wall_clock');
  end if;
  if coalesce(p_balls_merged, 0) > 20 and coalesce(p_duration_ms, 0) > 0
     and (coalesce(p_balls_merged, 0)::numeric / greatest(1, p_duration_ms)::numeric) > 0.015 then
    v_risk_level := 'SUSPICIOUS';
    v_risk_reasons := v_risk_reasons || jsonb_build_array('high_merge_frequency');
  end if;
  if coalesce(p_score, 0) > 50000 then
    v_risk_level := 'SUSPICIOUS';
    v_risk_reasons := v_risk_reasons || jsonb_build_array('outlier_high_score');
  end if;

  if v_uid is not null then
    v_score_id := public.record_user_score(
      p_score,
      p_tier_reached,
      p_balls_merged,
      least(greatest(0, coalesce(p_duration_ms, 0)), (v_elapsed_ms + 5000)::integer),
      null,
      coalesce(p_interruption_reason, 'completed'),
      p_collectibles,
      p_session_id
    );
    update public.game_sessions
    set status = 'completed',
        ended_at = now(),
        risk_level = v_risk_level,
        risk_reasons = v_risk_reasons,
        verified_score = greatest(0, coalesce(p_score, 0)),
        verified_tier = greatest(1, least(12, coalesce(p_tier_reached, 1))),
        verified_merges = greatest(0, coalesce(p_balls_merged, 0))
    where id = p_session_id;

    select * into v_progress from public.user_progress where user_id = v_uid;
    if round(least(2000000, greatest(0, coalesce(p_score, 0)))::numeric / 1000, 1) > 0 then
      insert into public.economy_ledger (user_id, session_id, delta, balance_after, coin_revision, reason)
      values (
        v_uid,
        p_session_id,
        round(least(2000000, greatest(0, coalesce(p_score, 0)))::numeric / 1000, 1),
        coalesce(v_progress.coins, 0),
        coalesce(v_progress.coin_revision, 0),
        'run_settlement'
      );
    end if;
    return jsonb_build_object(
      'score_id', v_score_id,
      'session_id', p_session_id,
      'risk_level', v_risk_level,
      'coins', coalesce(v_progress.coins, 0),
      'coin_revision', coalesce(v_progress.coin_revision, 0),
      'upgrades', coalesce(v_progress.upgrades, '{"wallDuration":0,"shakeDuration":0,"shakeIntensity":0}'::jsonb)
    );
  else
    v_score_id := public.record_guest_score(
      p_guest_id,
      p_score,
      p_tier_reached,
      p_balls_merged,
      least(greatest(0, coalesce(p_duration_ms, 0)), (v_elapsed_ms + 5000)::integer),
      null,
      coalesce(p_interruption_reason, 'completed'),
      p_collectibles,
      p_session_id
    );
    update public.game_sessions
    set status = 'completed',
        ended_at = now(),
        risk_level = v_risk_level,
        risk_reasons = v_risk_reasons,
        verified_score = greatest(0, coalesce(p_score, 0)),
        verified_tier = greatest(1, least(12, coalesce(p_tier_reached, 1))),
        verified_merges = greatest(0, coalesce(p_balls_merged, 0))
    where id = p_session_id;

    return jsonb_build_object(
      'score_id', v_score_id,
      'session_id', p_session_id,
      'risk_level', v_risk_level
    );
  end if;
end;
$$;
revoke all on function public.submit_game_session(uuid, integer, integer, integer, integer, text, jsonb, uuid, text) from public;
grant execute on function public.submit_game_session(uuid, integer, integer, integer, integer, text, jsonb, uuid, text) to anon, authenticated;

create or replace function public.claim_session_reward(p_session_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_settled numeric(20, 1);
  v_progress public.user_progress%rowtype;
begin
  if v_uid is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  perform public.boss_sync_user_progress_internal(v_uid, false);
  select * into v_progress from public.user_progress where user_id = v_uid;
  select coalesce(cs.credited_coins, 0) into v_settled
  from public.coin_settlements cs
  where cs.user_id = v_uid and cs.run_id = p_session_id
  limit 1;

  return jsonb_build_object(
    'session_id', p_session_id,
    'credited_coins', coalesce(v_settled, 0),
    'coins', coalesce(v_progress.coins, 0),
    'coin_revision', coalesce(v_progress.coin_revision, 0),
    'upgrades', coalesce(v_progress.upgrades, '{"wallDuration":0,"shakeDuration":0,"shakeIntensity":0}'::jsonb)
  );
end;
$$;
revoke all on function public.claim_session_reward(uuid) from public, anon, authenticated;
grant execute on function public.claim_session_reward(uuid) to authenticated;

