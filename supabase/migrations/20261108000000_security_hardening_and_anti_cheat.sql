-- Anti-cheat game session lifecycle and score validation RPCs
create or replace function public.start_game_session(
  p_guest_id uuid default null,
  p_seed text default null,
  p_theme text default 'classic',
  p_session_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_session_id uuid := coalesce(p_session_id, gen_random_uuid());
  v_nonce text := replace(gen_random_uuid()::text, '-', '');
  v_seed text := coalesce(nullif(btrim(p_seed), ''), replace(gen_random_uuid()::text, '-', ''));
  v_theme text := coalesce(nullif(btrim(p_theme), ''), 'classic');
  v_upgrades jsonb := '{"wallDuration":0,"shakeDuration":0,"shakeIntensity":0}'::jsonb;
  v_recent_count integer := 0;
  v_started_at timestamptz := now();
  v_expires_at timestamptz := now() + interval '12 hours';
begin
  if v_uid is null and p_guest_id is null then
    raise exception 'User or guest identity required' using errcode = '42501';
  end if;

  if v_uid is not null then
    select count(*) into v_recent_count
    from public.game_sessions
    where user_id = v_uid and started_at > now() - interval '1 minute';
    if v_recent_count >= 30 then
      raise exception 'Session creation rate limit exceeded' using errcode = 'P0001';
    end if;
    select up.upgrades into v_upgrades
    from public.user_progress up
    where up.user_id = v_uid;
    v_upgrades := coalesce(v_upgrades, '{"wallDuration":0,"shakeDuration":0,"shakeIntensity":0}'::jsonb);
  else
    select count(*) into v_recent_count
    from public.game_sessions
    where guest_id = p_guest_id and started_at > now() - interval '1 minute';
    if v_recent_count >= 30 then
      raise exception 'Session creation rate limit exceeded' using errcode = 'P0001';
    end if;
  end if;

  insert into public.game_sessions (
    id, user_id, guest_id, nonce, rules_version, seed, theme, upgrades_snapshot, status, started_at, expires_at
  )
  values (
    v_session_id, v_uid, case when v_uid is null then p_guest_id else null end,
    v_nonce, 1, v_seed, v_theme, v_upgrades, 'active', v_started_at, v_expires_at
  )
  on conflict (id) do nothing;

  return jsonb_build_object(
    'session_id', v_session_id,
    'nonce', v_nonce,
    'rules_version', 1,
    'seed', v_seed,
    'theme', v_theme,
    'upgrades', v_upgrades,
    'started_at', v_started_at,
    'expires_at', v_expires_at
  );
end;
$$;
revoke all on function public.start_game_session(uuid, text, text, uuid) from public;
grant execute on function public.start_game_session(uuid, text, text, uuid) to anon, authenticated;

