create or replace function public.activate_session_ability(
  p_session_id uuid,
  p_ability text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := (select auth.uid());
  v_ability text := btrim(coalesce(p_ability, ''));
  v_session public.game_sessions%rowtype;
  v_upgrades jsonb := '{"wallDuration":0,"shakeDuration":0,"shakeIntensity":0}'::jsonb;
  v_next_used jsonb;
  v_max_duration_ms integer := 0;
  v_intensity_mult numeric(6, 2) := 1.00;
begin
  if v_uid is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  if (select auth.jwt()->>'is_anonymous') = 'true' then
    raise exception 'Registered account required' using errcode = '42501';
  end if;
  if v_ability not in ('swap', 'shake', 'raise') then
    raise exception 'Unknown ability' using errcode = '22023';
  end if;

  select * into v_session
  from public.game_sessions gs
  where gs.id = p_session_id
  for update;

  if not found then
    select up.upgrades into v_upgrades
    from public.user_progress up
    where up.user_id = v_uid;
    v_upgrades := coalesce(v_upgrades, '{"wallDuration":0,"shakeDuration":0,"shakeIntensity":0}'::jsonb);

    insert into public.game_sessions (id, user_id, seed, theme, upgrades_snapshot, status)
    values (p_session_id, v_uid, replace(gen_random_uuid()::text, '-', ''), 'classic', v_upgrades, 'active')
    returning * into v_session;
  elsif v_session.user_id is distinct from v_uid then
    raise exception 'Session does not belong to authenticated user' using errcode = '42501';
  end if;
  if v_session.expires_at <= now() then
    update public.game_sessions set status = 'expired', ended_at = coalesce(ended_at, now()) where id = p_session_id;
    raise exception 'Game session has expired' using errcode = '22023';
  end if;
  if v_session.status <> 'active' then
    raise exception 'Game session is no longer active' using errcode = '22023';
  end if;
  if coalesce((v_session.abilities_used->>v_ability)::boolean, false) then
    raise exception 'Ability already used in this session' using errcode = '22023';
  end if;

  v_upgrades := coalesce(v_session.upgrades_snapshot, v_upgrades);
  if v_ability = 'raise' then
    v_max_duration_ms := 15000 + least(10, greatest(0, coalesce((v_upgrades->>'wallDuration')::integer, 0))) * 1000;
  elsif v_ability = 'shake' then
    v_max_duration_ms := 5000 + least(10, greatest(0, coalesce((v_upgrades->>'shakeDuration')::integer, 0))) * 500;
    v_intensity_mult := 1.00 + least(5, greatest(0, coalesce((v_upgrades->>'shakeIntensity')::integer, 0))) * 0.10;
  end if;

  v_next_used := jsonb_set(coalesce(v_session.abilities_used, '{}'::jsonb), array[v_ability], 'true'::jsonb, true);
  update public.game_sessions
  set abilities_used = v_next_used
  where id = p_session_id;

  return jsonb_build_object(
    'session_id', p_session_id,
    'ability', v_ability,
    'abilities_used', v_next_used,
    'upgrades', v_upgrades,
    'max_duration_ms', v_max_duration_ms,
    'intensity_multiplier', v_intensity_mult,
    'server_time', now()
  );
end;
$$;
