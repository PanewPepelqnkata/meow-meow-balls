-- Secure username -> email resolution RPC so profiles.email is not exposed to table SELECT
create or replace function public.resolve_username_email(p_username text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text;
begin
  if p_username is null or btrim(p_username) = '' then
    return null;
  end if;
  select p.email into v_email
  from public.profiles p
  where lower(p.username) = lower(btrim(p_username))
  limit 1;
  return v_email;
end;
$$;
revoke all on function public.resolve_username_email(text) from public;
grant execute on function public.resolve_username_email(text) to anon, authenticated;

-- Enforce boss_require_admin() on all boss_* RPCs that previously only checked auth.uid()
create or replace function public.boss_get_dashboard_data()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_profiles jsonb;
  v_scores jsonb;
  v_progress jsonb;
  v_guest_profiles jsonb;
  v_guest_scores jsonb;
begin
  perform public.boss_require_admin();

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', p.id,
        'username', p.username,
        'display_name', p.display_name,
        'email', coalesce(p.email, u.email),
        'avatar_url', p.avatar_url,
        'created_at', p.created_at,
        'updated_at', p.updated_at,
        'last_sign_in_at', u.last_sign_in_at
      )
      order by p.created_at desc
    ),
    '[]'::jsonb
  )
  into v_profiles
  from public.profiles p
  left join auth.users u on u.id = p.id;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', s.id,
        'user_id', s.user_id,
        'run_id', s.run_id,
        'score', s.score,
        'tier_reached', s.tier_reached,
        'balls_merged', s.balls_merged,
        'duration_ms', s.duration_ms,
        'interruption_reason', s.interruption_reason,
        'collectibles', s.collectibles,
        'created_at', s.created_at
      )
      order by s.created_at desc
    ),
    '[]'::jsonb
  )
  into v_scores
  from public.scores s;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'user_id', up.user_id,
        'best_score', up.best_score,
        'coins', up.coins,
        'coin_revision', up.coin_revision,
        'upgrades', up.upgrades,
        'discovered', up.discovered,
        'variants', up.variants,
        'stats', up.stats,
        'leaderboard', up.leaderboard,
        'settings', up.settings,
        'updated_at', up.updated_at
      )
    ),
    '[]'::jsonb
  )
  into v_progress
  from public.user_progress up;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'guest_id', gp.guest_id,
        'best_score', gp.best_score,
        'discovered', gp.discovered,
        'variants', gp.variants,
        'stats', gp.stats,
        'leaderboard', gp.leaderboard,
        'settings', gp.settings,
        'converted_user_id', gp.converted_user_id,
        'converted_at', gp.converted_at,
        'created_at', gp.created_at,
        'updated_at', gp.updated_at,
        'last_seen_at', gp.last_seen_at
      )
      order by gp.last_seen_at desc
    ),
    '[]'::jsonb
  )
  into v_guest_profiles
  from public.guest_profiles gp;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'id', gs.id,
        'guest_id', gs.guest_id,
        'run_id', gs.run_id,
        'score', gs.score,
        'tier_reached', gs.tier_reached,
        'balls_merged', gs.balls_merged,
        'duration_ms', gs.duration_ms,
        'interruption_reason', gs.interruption_reason,
        'collectibles', gs.collectibles,
        'created_at', gs.created_at
      )
      order by gs.created_at desc
    ),
    '[]'::jsonb
  )
  into v_guest_scores
  from public.guest_scores gs;

  return jsonb_build_object(
    'profiles', v_profiles,
    'scores', v_scores,
    'progress', v_progress,
    'guest_profiles', v_guest_profiles,
    'guest_scores', v_guest_scores,
    'generated_at', now()
  );
end;
$$;
revoke all on function public.boss_get_dashboard_data() from public, anon;
grant execute on function public.boss_get_dashboard_data() to authenticated;

