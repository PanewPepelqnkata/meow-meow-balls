-- Hardening RLS policies, privileges, admin RPC checks, and anti-cheat session ledger
revoke all on all tables in schema public from anon, authenticated;
alter default privileges in schema public revoke all on tables from anon, authenticated;

create table if not exists public.game_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete cascade,
  guest_id uuid,
  nonce text not null default replace(gen_random_uuid()::text, '-', ''),
  rules_version integer not null default 1,
  seed text not null,
  theme text not null,
  upgrades_snapshot jsonb not null default '{"wallDuration":0,"shakeDuration":0,"shakeIntensity":0}'::jsonb,
  status text not null default 'active' check (status in ('active', 'completed', 'aborted', 'rejected', 'expired')),
  risk_level text not null default 'NORMAL' check (risk_level in ('NORMAL', 'SUSPICIOUS', 'INVALID')),
  risk_reasons jsonb not null default '[]'::jsonb,
  started_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '12 hours'),
  ended_at timestamptz,
  verified_score integer not null default 0,
  verified_tier integer not null default 1,
  verified_merges integer not null default 0
);
alter table public.game_sessions enable row level security;
create index if not exists idx_game_sessions_user_started on public.game_sessions(user_id, started_at desc);
create index if not exists idx_game_sessions_guest_started on public.game_sessions(guest_id, started_at desc);

create table if not exists public.economy_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  session_id uuid references public.game_sessions(id) on delete set null,
  delta numeric(12, 1) not null,
  balance_after numeric(12, 1) not null,
  coin_revision bigint not null,
  reason text not null,
  created_at timestamptz not null default now()
);
alter table public.economy_ledger enable row level security;
create index if not exists idx_economy_ledger_user_created on public.economy_ledger(user_id, created_at desc);

